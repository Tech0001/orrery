/**
 * The Orrery mod's decisions (spec 2026-10-08-claude-code-mod sections 4.3-4.5, 11 and 12), with no import at all: Claude
 * Code loads this file into the mod's own environment (no Node), and vitest tests it.
 */

/** The id of the system-prompt section that carries the memory view. */
export const SECTION_ID = "orrery:memory";
/** The id of the system-prompt section that carries the agent's instructions; it goes before the memory section. */
export const INSTRUCTIONS_SECTION_ID = "orrery:instructions";
/** How long a view request may wait for summaries to catch up, in milliseconds. */
export const WAIT_MS = 30_000;
/**
 * How long the refetch after a turn's end may wait for this session's spool to drain (the holder taking the turn's final
 * reply in), in milliseconds. It waits for the spool alone, not for summaries.
 */
export const TURN_WAIT_MS = 5_000;
/** The one message kept when the last turn is empty. */
export const EMPTY_KEEP_TEXT = "(Orrery compacted this conversation; it continues from the memory view in the system prompt.)";
/** The text of a kept prompt row that had only an image (or nothing else that has text). */
export const IMAGE_KEEP_TEXT = "(an image; Orrery's compaction does not keep images)";
/** The text of a kept tool result that had no text: an image-only result, or a tool that printed nothing. */
export const RESULT_KEEP_TEXT = "(no text; Orrery's compaction does not keep images)";

/** How an agent records and compacts: "mod" (this mod compacts), "file" (CLAUDE.local.md import) or "none". */
export type Mode = "mod" | "file" | "none";

/** What a session's holder chose for it: it records the agent, or another window (or pi) does and it only reads. */
export type SessionMode = "recording" | "read-only";

/** Public remote status, matching src/remote/types.ts without importing Node into the mod runtime. */
export interface RemoteStatus {
	readonly remote: string;
	readonly state: "saved" | "pending" | "failing" | "lost";
	readonly savedAt?: string;
	readonly reason?: string;
	readonly movedTo?: string;
}

/** What `orrery claude-mod view` answered. */
export type ViewReply =
	| { readonly kind: "outside" }
	| {
			readonly kind: "lane";
			readonly lane: string;
			readonly mode: Mode;
			readonly compactAt: number;
			readonly messages: number;
			readonly remote?: RemoteStatus;
			readonly section: string | null;
			/** The agent's instructions section, or null when it has none; absent from an orrery that predates them. */
			readonly instructions?: string | null;
			/** Asked with the session (mod mode only): whether its turns reach memory. A compaction drops older turns only then. */
			readonly recording?: boolean;
			/** Asked with the session: what its mode file says; absent while the holder has not chosen yet. */
			readonly sessionMode?: SessionMode;
	  }
	| { readonly kind: "error"; readonly text: string };

/** One transcript row, as the mod reads it. */
export interface Row {
	readonly role: "user" | "assistant";
	readonly text: string;
	readonly toolUses: readonly unknown[];
	readonly toolResults?: readonly unknown[];
	readonly handle?: string;
}

/** A row the mod builds itself (the placeholder kept when nothing else is). */
export interface BuiltRow {
	readonly role: "user";
	readonly text: string;
	readonly toolUses: readonly [];
}

/** A kept row handed back built: its role, text and tool blocks, without the engine's handle. */
export type Rebuilt<R extends Row> = Pick<R, "role" | "text" | "toolUses" | "toolResults">;

/** What the mod does with a compaction: let Claude Code run it, skip it, or fetch the view and answer it. */
export type Route = "pass" | "skip" | "fetch";

/** Why the mod cannot answer a compaction, and the line for that. */
export interface Fallback {
	readonly kind: "fallback";
	readonly why: string;
	readonly line: string;
	/**
	 * Whether the cause lasts the session, so the mod stops starting compactions there. Only a last turn too large to
	 * keep does not: it passes with the next turn.
	 */
	readonly lasting: boolean;
}

/**
 * The mod's answer to a compaction: the rows to keep and the new section; why it cannot answer; or "pass", for a
 * session that never had a mod-mode agent and still has none (Claude Code compacts its own way, and nothing is said).
 */
export type Answer<R extends Row> =
	| { readonly kind: "answer"; readonly messages: readonly (R | Rebuilt<R> | BuiltRow)[]; readonly section: string; readonly line: string }
	| Fallback
	| { readonly kind: "pass" };

const NOT_PROMPTS = [
	/^<command-(name|message|args)>/,
	/^<local-command-(stdout|stderr|caveat)>/,
	/^Caveat: The messages below were generated by the user while running local commands/,
	/^This session is being continued from a previous conversation/,
	/^\[Request interrupted by user/,
];

/** Strips control characters and keeps at most 300 characters, so a line from outside is safe to show. */
export function plain(text: string): string {
	return text.replace(/[\u0000-\u001f\u007f-\u009f]/g, " ").slice(0, 300);
}

/**
 * The command that asks orrery for the view. The session and wait are added only when given; `spoolOnly` makes the wait
 * one for the session's spool alone, not for summaries. `agent` is the agent `orrery agent` opened this session as
 * (ORRERY_AGENT, and the token that tells the session from tools it starts), when Claude Code's environment has one.
 */
export function viewArgs(pluginRoot: string, cwd: string, session?: string, waitMs?: number, spoolOnly = false, agent?: { readonly name: string; readonly token?: string }): string[] {
	const args = ["sh", `${pluginRoot}/bin/orrery-run`, "claude-mod", "view", "--cwd", cwd];
	if (session !== undefined) args.push("--session", session);
	if (waitMs !== undefined && waitMs > 0) {
		args.push("--wait-ms", String(waitMs));
		if (spoolOnly) args.push("--spool-only");
	}
	if (agent !== undefined) {
		args.push("--agent", agent.name);
		if (agent.token !== undefined) args.push("--agent-token", agent.token);
	}
	return args;
}

/** Reads the view command's output into a ViewReply. Anything unexpected is an error reply. */
export function parseViewReply(run: { readonly exitCode: number; readonly stdout: string }): ViewReply {
	// orrery-run prints nothing when orrery is not installed: the plugin then does nothing (ruling 2).
	if (run.exitCode === 0 && run.stdout.trim() === "") return { kind: "outside" };
	let value: unknown;
	try {
		value = JSON.parse(run.stdout);
	} catch {
		return { kind: "error", text: `orrery answered something that is not JSON (exit ${run.exitCode})` };
	}
	if (typeof value !== "object" || value === null) return { kind: "error", text: "orrery answered something unexpected" };
	const v = value as Record<string, unknown>;
	if (typeof v.error === "string") return { kind: "error", text: plain(v.error) };
	if (v.lane === null) return { kind: "outside" };
	const modes = ["mod", "file", "none"];
	if (typeof v.lane !== "string" || !modes.includes(v.mode as string) || typeof v.compactAt !== "number" || typeof v.messages !== "number" || !(v.section === null || typeof v.section === "string")) {
		return { kind: "error", text: "orrery answered something unexpected" };
	}
	if ("recording" in v && typeof v.recording !== "boolean") return { kind: "error", text: "orrery answered something unexpected" };
	if ("sessionMode" in v && v.sessionMode !== "recording" && v.sessionMode !== "read-only") return { kind: "error", text: "orrery answered something unexpected" };
	if ("instructions" in v && !(v.instructions === null || typeof v.instructions === "string")) return { kind: "error", text: "orrery answered something unexpected" };
	let remote: { remote?: RemoteStatus } = {};
	if ("remote" in v) {
		if (v.remote === null || typeof v.remote !== "object") return { kind: "error", text: "orrery answered something unexpected" };
		const r = v.remote as Record<string, unknown>;
		if (typeof r.remote !== "string" || !["saved", "pending", "failing", "lost"].includes(r.state as string) || [r.savedAt, r.reason, r.movedTo].some((field) => field !== undefined && typeof field !== "string")) {
			return { kind: "error", text: "orrery answered something unexpected" };
		}
		remote = { remote: {
			remote: r.remote, state: r.state as RemoteStatus["state"],
			...(typeof r.savedAt === "string" ? { savedAt: r.savedAt } : {}),
			...(typeof r.reason === "string" ? { reason: r.reason } : {}),
			...(typeof r.movedTo === "string" ? { movedTo: r.movedTo } : {}),
		} };
	}
	const recording = typeof v.recording === "boolean" ? { recording: v.recording } : {};
	const sessionMode: { sessionMode?: SessionMode } = v.sessionMode === "recording" || v.sessionMode === "read-only" ? { sessionMode: v.sessionMode } : {};
	const instructions: { instructions?: string | null } = v.instructions === null || typeof v.instructions === "string" ? { instructions: v.instructions } : {};
	return { kind: "lane", lane: v.lane, mode: v.mode as Mode, compactAt: v.compactAt, messages: v.messages, section: v.section as string | null, ...recording, ...sessionMode, ...instructions, ...remote };
}

/** True when a row is a real prompt from the user, not a tool result, a reminder-only row or Claude Code's own rows. */
export function isTurnStart(row: Row): boolean {
	if (row.role !== "user" || (row.toolResults?.length ?? 0) > 0) return false;
	const text = row.text.replace(/<system-reminder>[\s\S]*?<\/system-reminder>/g, "").trim();
	if (text === "" || text === EMPTY_KEEP_TEXT) return false;
	return !NOT_PROMPTS.some((pattern) => pattern.test(text));
}

/** The rows from the last real prompt to the end; empty when there is no prompt. */
export function lastTurn<R extends Row>(rows: readonly R[]): R[] {
	for (let i = rows.length - 1; i >= 0; i--) if (isTurnStart(rows[i] as R)) return rows.slice(i);
	return [];
}

/** Whether a row has nothing the mod reads: no text, no tool calls, no tool results (a thinking-only reply, an image). */
function empty(row: Row): boolean {
	return row.text === "" && row.toolUses.length === 0 && (row.toolResults?.length ?? 0) === 0;
}

/** Whether a user row is a note, neither a prompt nor tool results: an interruption, a command row, its output, a reminder. */
function isNote(row: Row): boolean {
	return row.role === "user" && (row.toolResults?.length ?? 0) === 0 && !isTurnStart(row);
}

/**
 * Whether a turn is still in progress: the model has not given its final answer. Walking back past rows that carry
 * nothing and past notes (Esc adds "[Request interrupted by user…]" after a tool's result, or the model was stopped while
 * thinking), the last real row calls tools or carries their results. Only Claude Code's own threshold, or an Esc in the
 * tool loop, leaves a turn so.
 */
export function inProgress(rows: readonly Row[]): boolean {
	for (let i = rows.length - 1; i >= 0; i--) {
		const row = rows[i] as Row;
		if (empty(row) || isNote(row)) continue;
		return row.toolUses.length > 0 || (row.toolResults?.length ?? 0) > 0;
	}
	return false;
}

/** A tool result with its text, or a placeholder where it had none (an image-only result, or no output at all). */
function keptResult(result: unknown): unknown {
	if (typeof result !== "object" || result === null || (result as { text?: unknown }).text !== "") return result;
	return { ...result, text: RESULT_KEEP_TEXT };
}

/**
 * A kept row handed back built: role, text and tool blocks, and no handle. Claude Code keeps a row handed back with its
 * handle together with everything it attached after it, its system-prompt snapshot among them, and its requests then
 * keep sending that snapshot's prompt, the old memory section included. A built row carries only these fields, so the
 * next request composes the prompt afresh. A prompt row or a tool result with no text gets a placeholder.
 */
function rebuilt<R extends Row>(row: R): Rebuilt<R> {
	const text = row.role === "user" && empty(row) ? IMAGE_KEEP_TEXT : row.text;
	const fields = { role: row.role, text, toolUses: row.toolUses };
	return (row.toolResults === undefined ? fields : { ...fields, toolResults: row.toolResults.map(keptResult) }) as Rebuilt<R>;
}

/** Whether a kept row is handed back: all but a thinking-only reply, which has nothing once built. */
function handedBack(row: Row): boolean {
	return !(row.role === "assistant" && empty(row));
}

/** What a value that cannot be serialized counts as, in characters: large, so a keep it is part of is not taken lightly. */
const UNSERIALIZABLE = 100_000;

/** The characters of `value` written as JSON; 0 when it is absent. */
function size(value: unknown): number {
	if (value === undefined) return 0;
	try {
		return JSON.stringify(value)?.length ?? UNSERIALIZABLE;
	} catch {
		return UNSERIALIZABLE;
	}
}

/** The characters of a text field: its length, or its JSON size when it is not a string. */
function chars(value: unknown): number {
	return typeof value === "string" ? value.length : size(value);
}

/** A field of an object read defensively (the rows' tool lists are typed as unknown here). */
function field(value: unknown, key: string): unknown {
	return typeof value === "object" && value !== null ? (value as Record<string, unknown>)[key] : undefined;
}

/**
 * A rough token count: characters divided by four. It counts each row's text, each tool call's input, and each tool's
 * output once, as the model read it: a tool result's `text`, or the tool use's own `text` when its result row is not
 * among `rows`. Claude Code also stores outputs as `result` records, in both places; those are not what the model
 * read, and are not counted.
 */
export function estimateTokens(rows: readonly Row[]): number {
	const answered = new Set<unknown>();
	for (const row of rows) for (const result of row.toolResults ?? []) answered.add(field(result, "tool_use_id"));
	let total = 0;
	for (const row of rows) {
		total += row.text.length;
		for (const use of row.toolUses) {
			total += size(field(use, "input"));
			const id = field(use, "tool_use_id");
			if (id === undefined || !answered.has(id)) total += chars(field(use, "text"));
		}
		for (const result of row.toolResults ?? []) total += chars(field(result, "text"));
	}
	return Math.ceil(total / 4);
}

/** Decides what to do with a compaction given its trigger, whether it comes from a subagent, and the view reply. */
export function compactRoute(trigger: string, agentId: string | undefined, reply: ViewReply | undefined): Route {
	if (agentId !== undefined) return "pass";
	if (reply?.kind === "outside" || (reply?.kind === "lane" && reply.mode !== "mod")) return "pass";
	if (trigger === "precompute") return reply?.kind === "lane" ? "skip" : "pass";
	return "fetch";
}

function fallback(why: string, lasting = true): Fallback {
	return { kind: "fallback", why, line: fallbackLine(why), lasting };
}

/** Whether a reply is a mod-mode agent's. */
function modAgent(reply: ViewReply | undefined): boolean {
	return reply?.kind === "lane" && reply.mode === "mod";
}

/**
 * Builds the answer to a compaction from the view `reply` fetched for it: the last turn kept, the new memory section,
 * and one status line. `held` is what the session learned first (or at its last compaction).
 */
export function compactAnswer<R extends Row>(messages: readonly R[], reply: ViewReply, held?: ViewReply): Answer<R> {
	if (reply.kind === "error") return fallback(`the memory view could not be read: ${reply.text}`);
	// The first fetch failed and the folder has no mod agent after all: nothing of Orrery's to answer, and nothing to say.
	if (held !== undefined && !modAgent(held) && !modAgent(reply)) return { kind: "pass" };
	if (held?.kind === "lane" && reply.kind === "lane" && reply.lane !== held.lane) return fallback("this session's folder now belongs to another agent");
	if (reply.kind === "outside" || reply.mode !== "mod") return fallback("this folder's agent is no longer in mod mode");
	// A session that is not recorded (read-only, or its holder gone with events spooled): the older turns are not all in
	// memory, so they must not be dropped.
	if (reply.recording === false) return fallback("this session is not recorded");
	if (reply.section === null) return fallback("the agent has no memory yet");
	const kept = lastTurn(messages);
	const tokens = estimateTokens(kept);
	if (tokens > reply.compactAt / 2) return fallback(`the last turn is too large to keep (about ${tokens} tokens)`, false);
	// A finished turn goes back built, without its images, thinking and attachments, so the new section reaches the model.
	// A turn still in progress stays as Claude Code has it, so its unfinished tool loop keeps its thinking; the section can
	// then stay stale until the next compaction.
	const handed: readonly (R | Rebuilt<R>)[] = inProgress(kept) ? kept : kept.filter(handedBack).map(rebuilt);
	const built: BuiltRow = { role: "user", text: EMPTY_KEEP_TEXT, toolUses: [] };
	return {
		kind: "answer",
		messages: handed.length > 0 ? handed : [built],
		section: reply.section,
		line: `Orrery compacted: kept the last turn (${handed.length} messages); memory view refreshed (${reply.messages} messages).`,
	};
}

/** True when the mod should start a compaction: the agent is in mod mode and the context passed compact_at. */
export function shouldCompact(tokens: number | undefined, reply: ViewReply | undefined): boolean {
	return tokens !== undefined && reply?.kind === "lane" && reply.mode === "mod" && tokens > reply.compactAt;
}

/** The status line for a compaction that Orrery could not answer. */
export function fallbackLine(why: string): string {
	return `Orrery could not compact this conversation (${plain(why)}); Claude Code compacts it its own way.`;
}

/** The status line for a compaction the mod started itself and could not answer for now (the cause is not lasting): it is skipped, and the mod tries again later. */
export function laterLine(why: string): string {
	return `Orrery could not compact this conversation (${plain(why)}); it stays as it is for now.`;
}

/** The status line for a compaction the mod started itself and could not answer: it is skipped, not handed to Claude Code. */
export function skipLine(why: string): string {
	return `Orrery could not compact this conversation (${plain(why)}); it stays as it is, and Orrery will not start compactions in this session.`;
}

/** The status line for a memory section that could not be placed in the prompt. */
export function sectionFailedLine(text: string): string {
	return `Orrery: no memory in this session's prompt (${plain(text)}). Recording is not affected.`;
}

/** The status line for a session where the mod stops starting compactions. */
export function stopLine(reason: string): string {
	return `Orrery will not start compactions in this session (${plain(reason)}); /compact still uses Orrery.`;
}

// Showing that the mod is loaded (spec sections 11 and 12): the startup band above the prompt, the footer label with
// the agent's message count, and the compaction line where it can be seen. All three only in a mod-mode agent.

/** The first word of the footer's mode label in a mod-mode agent's session. */
export const MODE_LABEL = "Orrery";
/** The band's words for a window whose session the holder made read-only. */
export const READ_ONLY_STATE = "read-only (another window records this agent)";
/** The least room, in cells, the band needs to draw the logo beside its lines. */
export const BAND_LOGO_COLUMNS = 60;
export const BAND_LOGO_ROWS = 5;

/** A mod-mode agent's reply, narrowed. */
type ModAgentReply = Extract<ViewReply, { kind: "lane" }>;

function asModAgent(reply: ViewReply | undefined): ModAgentReply | undefined {
	return reply?.kind === "lane" && reply.mode === "mod" ? reply : undefined;
}

/**
 * The startup band's two lines for the session's `reply`: `Orrery · <Agent>`, then the memory and the session's mode as
 * its mode file says (left out while not known). Undefined outside a mod-mode agent: no band.
 */
export function bandLines(reply: ViewReply | undefined): readonly [string, string] | undefined {
	const shown = asModAgent(reply);
	if (shown === undefined) return undefined;
	const memory = shown.section === null ? "no memory yet" : `memory loaded · ${shown.messages} msgs${shown.remote === undefined ? "" : ` · ${remoteFooter(shown.remote)}`}`;
	const mode = shown.sessionMode === "recording" ? " · recording" : shown.sessionMode === "read-only" ? ` · ${READ_ONLY_STATE}` : "";
	return [`Orrery · ${plain(shown.lane)}`, `${memory}${mode}`];
}

/** Whether the band still waits to learn the session's mode: a mod-mode agent whose session had no mode file when last asked. */
export function bandWaitsForMode(reply: ViewReply | undefined): boolean {
	const shown = asModAgent(reply);
	return shown !== undefined && shown.sessionMode === undefined;
}

/**
 * Whether the band asks orrery again, after the answer `reply`: it has no answer yet or only an error (orrery did not
 * answer), or a mod-mode agent's session mode is not known yet.
 */
export function bandAsksAgain(reply: ViewReply | undefined): boolean {
	return reply === undefined || reply.kind === "error" || bandWaitsForMode(reply);
}

/** Whether the band shows: it has lines, the person has sent no prompt in this process yet, and no survey holds the band. */
export function bandShows(lines: readonly [string, string] | undefined, state: { readonly prompted: boolean; readonly hasSurvey: boolean }): boolean {
	return lines !== undefined && !state.prompted && !state.hasSurvey;
}

/** Whether a prompt's origin is the person's own (Enter at the prompt, or the Remote Control bridge): it ends the band. */
export function personPrompt(origin: string): boolean {
	return origin === "composer" || origin === "bridge";
}

/** Whether the band draws the logo beside its lines: on the terminal, with room for it; elsewhere the lines show alone. */
export function bandHasLogo(surface: string, columns: number, rows: number): boolean {
	return surface === "terminal" && columns >= BAND_LOGO_COLUMNS && rows >= BAND_LOGO_ROWS;
}

/** Node-free equivalent of remote/checkout.remoteFooter; the view command already sanitizes these public fields. */
function remoteFooter(status: RemoteStatus): string {
	const remote = plain(status.remote);
	if (status.state === "lost") return `${remote}: moved to ${plain(status.movedTo ?? "another machine")}`;
	if (status.state === "failing") return `${remote} ⚠ not saved: ${plain(status.reason ?? "unknown error")}`;
	if (status.state === "pending") return `${remote} · not saved yet`;
	return `${remote} ✓${status.savedAt === undefined ? "" : ` ${plain(status.savedAt)}`}`;
}

/** The footer's mode label for the session's `reply`, as pi's status reads: `Orrery · <Agent> · <N> msgs`. Undefined outside a mod-mode agent. */
export function footerLabel(reply: ViewReply | undefined): string | undefined {
	const shown = asModAgent(reply);
	return shown === undefined ? undefined : `${MODE_LABEL} · ${plain(shown.lane)} · ${shown.messages} msgs${shown.remote === undefined ? "" : ` · ${remoteFooter(shown.remote)}`}`;
}

/** Whether a mode label is Orrery's: its own word alone, or followed by the agent and count. */
function orreryMode(mode: string): boolean {
	return mode === MODE_LABEL || mode.startsWith(`${MODE_LABEL} · `);
}

/**
 * The footer's mode labels with Orrery's current label, in a mod-mode agent: exactly one, any Orrery label already among
 * them replaced. Undefined to leave them as they are.
 */
export function footerModes(modes: readonly string[], reply: ViewReply | undefined): readonly string[] | undefined {
	const label = footerLabel(reply);
	if (label === undefined) return undefined;
	return [...modes.filter((mode) => !orreryMode(mode)), label];
}

/**
 * Whether a turn's end asks orrery for the footer's count again: a turn of the main loop (`agentId` absent), in a
 * session whose facts say mod-mode agent. A subagent's turn, a folder outside any agent, a file-mode agent, or a session
 * with no facts yet (or only an error) runs nothing.
 */
export function turnRefetches(agentId: string | undefined, reply: ViewReply | undefined): boolean {
	return agentId === undefined && asModAgent(reply) !== undefined;
}

/**
 * Whether the session draws anywhere, from `$.session.surfaces()` (it follows clients attaching and detaching): a
 * session that draws nowhere (`claude -p`, the SDK with no client attached) has no label to keep current.
 */
export function drawsSomewhere(surfaces: readonly string[]): boolean {
	return surfaces.length > 0;
}

/**
 * Whether a turn's refetch answer replaces what the label shows: only a mod-mode agent's. Anything else (outside any
 * agent, as when orrery is briefly not there; an agent switched out of mod mode mid-session; an error) keeps the label and
 * its count, and the refetches after later turns.
 */
export function turnReplyShown(reply: ViewReply): boolean {
	return footerLabel(reply) !== undefined;
}
